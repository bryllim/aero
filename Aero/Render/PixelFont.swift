import Foundation

/// A 7-row dot-matrix typeface. Glyphs are 5 dots wide except the narrow punctuation.
enum PixelFont {
    static let rows = 7

    /// The colon while it is blinked off: same width as ":" with no dots lit.
    static let blankColon: Character = "¦"

    static func glyph(_ character: Character) -> [[Bool]] {
        glyphs[character] ?? glyphs[" "]!
    }

    /// Dot columns the text occupies, with one blank column between glyphs.
    static func columns(_ text: String) -> Int {
        text.reduce(0) { $0 + glyph($1)[0].count } + max(text.count - 1, 0)
    }

    /// The text as rows of lit/unlit dots.
    static func bitmap(_ text: String) -> [[Bool]] {
        var out = [[Bool]](repeating: [], count: rows)
        for (index, character) in text.enumerated() {
            let g = glyph(character)
            for row in 0..<rows {
                if index > 0 { out[row].append(false) }
                out[row].append(contentsOf: g[row])
            }
        }
        return out
    }

    private static let glyphs: [Character: [[Bool]]] = source.mapValues { lines in
        lines.map { $0.map { $0 == "#" } }
    }

    private static let source: [Character: [String]] = [
